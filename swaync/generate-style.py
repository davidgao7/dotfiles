def main() -> None:
    # Determine wallpaper path
    wallpaper = sys.argv[1] if len(sys.argv) > 1 else get_wallpaper_path()
    if not wallpaper or not Path(wallpaper).exists():
        print(f"Error: no valid wallpaper found ({wallpaper or 'none'})")
        sys.exit(1)

    print(f"Generating colors from: {Path(wallpaper).name}")
    colors = generate_colors(wallpaper)

    # Write style.css
    css = CSS_TEMPLATE.format(source=Path(wallpaper).name, **colors)
    OUTPUT.write_text(css)
    print(f" wrote: {OUTPUT}")

    # Reload swaync
    try:
        subprocess.run(SWAYNC_RELOAD, check=False, timeout=5)
        print(" reloaded swaync")
    except Exception as e:
        print(f" warning: swaync reload failed ({e})")


if __name__ == "__main__":
    main()
