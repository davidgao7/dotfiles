#!/usr/bin/env python3
"""
Generate swaync style.css with Material You colors from the current awww wallpaper.
Usage: python generate-style.py [path/to/wallpaper]
  If no path given, auto-detects from `awww query`.
"""

import sys
import subprocess
from pathlib import Path

from PIL import Image
from materialyoucolor.scheme.scheme import Scheme
from materialyoucolor.palettes.core_palette import CorePalette


OUTPUT = Path(__file__).resolve().parent / "style.css"
SWAYNC_RELOAD = ["swaync-client", "--reload-css"]


def argb_to_hex(argb: int) -> str:
    """Convert ARGB int (0xAARRGGBB) to #RRGGBB hex string."""
    return f"#{((argb >> 16) & 0xFF):02X}{((argb >> 8) & 0xFF):02X}{(argb & 0xFF):02X}"


def get_wallpaper_path() -> str | None:
    """Get current wallpaper path from awww query."""
    try:
        out = subprocess.check_output(["awww", "query"], text=True, timeout=3)
        for line in out.strip().splitlines():
            if "currently displaying: image:" in line:
                return line.split("image:")[1].strip()
    except Exception:
        pass
    return None


def generate_colors(image_path: str) -> dict[str, str]:
    """
    Extract Material You dark scheme colors from an image.
    Returns a dict of hex color strings keyed by token name.
    """
    from materialyoucolor.quantize import QuantizeCelebi
    from materialyoucolor.score.score import Score

    # Load and resize image for fast processing
    img = Image.open(image_path).convert("RGBA")
    img.thumbnail((112, 112))

    # Get pixels as list of [r, g, b, a] — the format QuantizeCelebi expects
    pixels_rgba = [list(px) for px in img.getdata() if px[3] >= 128]

    if not pixels_rgba:
        raise ValueError("No non-transparent pixels found in image")

    # Quantize to find dominant colors, then score and pick the best source color
    quantized = QuantizeCelebi(pixels_rgba, 128)
    ranked = Score.score(quantized)
    source_argb = ranked[0]

    # Build dark scheme
    scheme = Scheme.dark(source_argb)

    # Also get the core palette for surfaceContainer tones
    core = CorePalette.of(source_argb)

    def tone(hex_val: int) -> str:
        return argb_to_hex(hex_val)

    return {
        # Directly from Scheme
        "surface": tone(scheme.surface),
        "onSurface": tone(scheme.on_surface),
        "surfaceVariant": tone(scheme.surface_variant),
        "onSurfaceVariant": tone(scheme.on_surface_variant),
        "outline": tone(scheme.outline),
        "outlineVariant": tone(scheme.outline_variant),
        "primary": tone(scheme.primary),
        "onPrimary": tone(scheme.on_primary),
        "primaryContainer": tone(scheme.primary_container),
        "onPrimaryContainer": tone(scheme.on_primary_container),
        "error": tone(scheme.error),
        "errorContainer": tone(scheme.error_container),
        "onErrorContainer": tone(scheme.on_error_container),
        # Approximated: surfaceContainer ≈ one step above surface
        "surfaceContainer": tone(core.n1.tone(12)),
        "surfaceContainerHigh": tone(core.n1.tone(17)),
        "surfaceContainerHighest": tone(core.n1.tone(22)),
    }


